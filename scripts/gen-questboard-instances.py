#!/usr/bin/env python3
"""Writes server/npc/custom/questboard_instances.txt: the instances the quest board's fourth card (npc/custom/
questboard.txt) can send a character to, from the server's own data. For every instance in db/re/instance_db.yml
whose entry NPC is found (the NPC whose script calls instance_create for it, on an ordinary map): its name, the
lowest base level its script lets in (the highest `BaseLevel < N` near the call; for one without, the mean level of
its monsters), the entry NPC's name, map and cell, and the instance's maps (a boss falling on one completes the card).
The map names come from the game's map name table (data/mapnametable.txt; the app keeps a copy in its files folder).

Usage: scripts/gen-questboard-instances.py <mapnametable.txt>   (RATHENA_DIR=<checkout> for another server)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATHENA = os.environ.get("RATHENA_DIR", os.path.join(ROOT, "server"))
OUT = os.path.join(RATHENA, "npc/custom/questboard_instances.txt")
HEADER = re.compile(r"^([a-z0-9_@]+),(\d+),(\d+),\d+\t(?:script|duplicate\([^)]*\))\t([^\t]+)\t", re.M)


def loaded(conf, seen):
    files = []
    for line in open(os.path.join(RATHENA, conf), errors="ignore"):
        line = line.split("//")[0].strip()
        m = re.match(r"(npc|import):\s*(\S+)", line)
        if not m or m.group(2) in seen:
            continue
        seen.add(m.group(2))
        files += loaded(m.group(2), seen) if m.group(1) == "import" else [m.group(2)]
    return [f for f in files if os.path.isfile(os.path.join(RATHENA, f))]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    names = {}
    for line in open(sys.argv[1], encoding="utf-8", errors="ignore"):
        parts = line.strip().split("#")
        if len(parts) >= 2 and parts[0].endswith(".rsw"):
            names[parts[0][:-4].lower()] = parts[1]

    instances = {}
    for blk in open(os.path.join(RATHENA, "db/re/instance_db.yml")).read().split("\n  - Id: ")[1:]:
        name = re.search(r"\n    Name: (.+)", blk).group(1).strip().strip('"')
        enter = re.search(r"\n      Map: (\S+)", blk)
        extra = re.findall(r"\n      (\S+): true", blk)
        if enter:
            instances[name] = [enter.group(1)] + extra

    # monster levels, for an instance whose script checks no level
    mob_lv = {}
    for blk in open(os.path.join(RATHENA, "db/re/mob_db.yml"), errors="ignore").read().split("\n  - Id: ")[1:]:
        lv = re.search(r"\n    Level: (\d+)", blk)
        mob_lv[blk.split("\n")[0].split()[0]] = int(lv.group(1)) if lv else 0

    rows = []
    for f in loaded("npc/re/scripts_main.conf", set()):
        text = open(os.path.join(RATHENA, f), errors="ignore").read()
        if "instance_create" not in text:
            continue
        heads = list(HEADER.finditer(text))
        for i, h in enumerate(heads):
            block = text[h.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
            if "instance_create" not in block or "@" in h.group(1):
                continue
            called = set(re.findall(r'instance_create\(\s*"([^"]+)"', block))
            called |= set(re.findall(r'\.@md_name\$\s*(?:=|,)\s*"([^"]+)"', block))
            called |= set(re.findall(r'\.@md_name\$\s*=\s*"([^"]+)"', text)) if "instance_create(.@md_name$" in block else set()
            for inst in sorted(called):
                if inst not in instances or any(r[0] == inst for r in rows):
                    continue
                # the entry NPC's own gate, else the lowest in its file (a helper NPC beside it keeps it)
                gates = [int(n) for n in re.findall(r"BaseLevel\s*<\s*(\d+)", block)]
                file_gates = [int(n) for n in re.findall(r"BaseLevel\s*<\s*(\d+)", text)]
                level = max(gates) if gates else (min(file_gates) if file_gates else 0)
                if not level:
                    lvs = [mob_lv.get(m, 0) for m in re.findall(r'monster\s+"?[0-9]*@?[^,"]*"?,[^;]*?,\s*(\d+)\s*,', text)]
                    lvs = [l for l in lvs if l]
                    level = round(sum(lvs) / len(lvs)) if lvs else 0
                if not level:
                    continue
                npc = h.group(4).split("#")[0].split("::")[0].strip()
                where = names.get(h.group(1), h.group(1)).split(",")[0].strip()
                rows.append((inst, level, npc, h.group(1), where, int(h.group(2)), int(h.group(3)), ",".join(instances[inst])))
    rows.sort(key=lambda r: r[1])

    out = [
        "//===== rAthena Script =======================================",
        "//= Quest board: the instances",
        "//===== Description: =========================================",
        "//= Generated by scripts/gen-questboard-instances.py from",
        "//= instance_db and the instances' scripts: do not edit.",
        "//= npc/custom/questboard.txt is what uses them.",
        "//============================================================",
        "",
        "// by level: name, the least base level, the entry NPC, its map (and the map's name) and cell, the instance's",
        "// maps",
        "-\tscript\tQuestBoardInstances\t-1,{",
        "OnInit:",
    ]
    q = lambda v: '"' + str(v).replace('"', "'") + '"'
    for i in range(0, len(rows), 20):
        c = rows[i:i + 20]
        out.append(f"\tsetarray $@qi_name$[{i}], " + ", ".join(q(r[0]) for r in c) + ";")
        out.append(f"\tsetarray $@qi_lv[{i}], " + ", ".join(str(r[1]) for r in c) + ";")
        out.append(f"\tsetarray $@qi_npc$[{i}], " + ", ".join(q(r[2]) for r in c) + ";")
        out.append(f"\tsetarray $@qi_map$[{i}], " + ", ".join(q(r[3]) for r in c) + ";")
        out.append(f"\tsetarray $@qi_where$[{i}], " + ", ".join(q(r[4]) for r in c) + ";")
        out.append(f"\tsetarray $@qi_x[{i}], " + ", ".join(str(r[5]) for r in c) + ";")
        out.append(f"\tsetarray $@qi_y[{i}], " + ", ".join(str(r[6]) for r in c) + ";")
        out.append(f"\tsetarray $@qi_maps$[{i}], " + ", ".join(q(r[7]) for r in c) + ";")
    out += ["\tend;", "}"]
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"{len(rows)} instances -> {os.path.relpath(OUT, ROOT)}")
    for r in rows:
        print(f"  {r[1]:3}  {r[0]}  ({r[2]}, {r[4]} {r[5]},{r[6]})")


if __name__ == "__main__":
    main()
