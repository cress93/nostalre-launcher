#!/usr/bin/env python3
"""Writes server/npc/custom/appraiser_points.txt: where the Appraiser (npc/custom/appraiser.txt) stands. Beside every
Tool Dealer the server loads, behind the same counter (two or three cells to its side, on a walkable cell no other
NPC stands on); and by the Kafra spot of every town of the Kafra network (npc/custom/waypoint_points.txt, from
scripts/gen-waypoints.py: run that first) with no Tool Dealer on the town map itself, as Prontera's is indoors.

Usage: scripts/gen-appraisers.py   (RATHENA_DIR=<checkout> for another server than server/)
"""
import importlib.util
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATHENA = os.environ.get("RATHENA_DIR", os.path.join(ROOT, "server"))
OUT = os.path.join(RATHENA, "npc/custom/appraiser_points.txt")
SPRITE = "4_M_SAGE_A"
# a town's Appraiser somewhere else than by the teleport spot: Prontera's in the market, by the quest board
TOWN_AT = {"prontera": (147, 183)}
# rAthena's directions, 0 north counter-clockwise: the cell step each faces
STEP = {0: (0, 1), 1: (-1, 1), 2: (-1, 0), 3: (-1, -1), 4: (0, -1), 5: (1, -1), 6: (1, 0), 7: (1, 1)}
NPC = re.compile(r"([a-z0-9_]+),(\d+),(\d+),(\d+)\t(shop|script|duplicate\([^)]*\)|cashshop|itemshop|pointshop|warp2?)\t([^\t]+)\t(-?[\w]+)")


def main():
    spec = importlib.util.spec_from_file_location("waypoints", os.path.join(ROOT, "scripts/gen-waypoints.py"))
    waypoints = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(waypoints)
    cells = waypoints.map_cells(os.path.join(RATHENA, "db/map_cache.dat"))
    cells.update(waypoints.map_cells(os.path.join(RATHENA, "db/re/map_cache.dat")))

    taken, dealers = set(), []
    for f in waypoints.loaded("npc/re/scripts_main.conf", set()):
        # not where the last run put the Appraisers: they would be in their own way
        if os.path.join(RATHENA, f) == OUT:
            continue
        for line in open(os.path.join(RATHENA, f), errors="ignore"):
            m = NPC.match(line)
            if not m:
                continue
            where = (m.group(1), int(m.group(2)), int(m.group(3)))
            taken.add(where)
            if m.group(6).split("#")[0] == "Tool Dealer" and m.group(7) != "-1" and where[0] in cells \
                    and not waypoints.NOT_A_PLACE.search(where[0]):
                dealers.append((*where, int(m.group(4)) % 8))

    def free(map_name, x, y):
        return waypoints.walkable(cells, map_name, x, y) and (map_name, x, y) not in taken

    out = [
        "//===== rAthena Script =======================================",
        "//= Appraiser: where it stands",
        "//===== Description: =========================================",
        "//= Generated by scripts/gen-appraisers.py from the Tool",
        "//= Dealers, the Kafra network's towns and the map cache: do",
        "//= not edit. npc/custom/appraiser.txt is the Appraiser.",
        "//============================================================",
        "",
    ]

    def place(map_name, x, y, d, key):
        taken.add((map_name, x, y))
        out.append(f"{map_name},{x},{y},{d}\tduplicate(Appraiser)\tAppraiser#{key}\t{SPRITE}")

    on_town = set()
    for n, (map_name, x, y, d) in enumerate(sorted(set(dealers))):
        dx, dy = STEP[d]
        # beside it, facing the same way: across the counter from the customers, as it is
        spot = next(((x + sx * r, y + sy * r) for r in (2, 3, 1) for sx, sy in ((-dy, dx), (dy, -dx))
                     if free(map_name, x + sx * r, y + sy * r)), None)
        if spot is None:
            near = waypoints.spot_near(cells, map_name, x, y, 1)
            spot = near[0] if near and free(map_name, *near[0]) else None
        if spot is None:
            print(f"no spot by the Tool Dealer on {map_name},{x},{y}")
            continue
        place(map_name, *spot, d, f"td{n}")
        on_town.add(map_name)

    table = open(os.path.join(RATHENA, "npc/custom/waypoint_points.txt")).read()

    def arr(name):
        values = []
        for chunk in re.findall(r"\$@" + re.escape(name) + r"\[\d+\], (.*);", table):
            values += re.findall(r'"([^"]*)"|(-?\d+)', chunk)
        return [a or b for a, b in values]

    towns = 0
    for town, x, y, dungeon in zip(arr("way_map$"), arr("way_x"), arr("way_y"), arr("way_dungeon")):
        if dungeon != "0" or town in on_town:
            continue
        x, y = int(x), int(y)
        # a few steps off the spot teleports land on
        spot = TOWN_AT.get(town) or next(((cx, cy) for r in (3, 4, 5, 6)
                                          for cx, cy in ((x + r, y), (x - r, y), (x, y + r), (x, y - r))
                                          if free(town, cx, cy)), None)
        if spot is None:
            print(f"no spot in {town}")
            continue
        place(town, *spot, 4, town)
        towns += 1
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"{len(out) - 8 - towns} by Tool Dealers, {towns} in towns -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
