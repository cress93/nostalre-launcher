#!/usr/bin/env python3
"""nostalre-client's map monster tables (lib/game/src/map_monster_tables.rs) from rAthena's Renewal spawns.

Every map's permanent monster spawns (the npc files npc/re/scripts_main.conf loads, `monster` and `boss_monster`
lines) with how many of each, and each monster's English name, level and whether it is a boss or MVP
(db/re/mob_db.yml), for the world map's map info.

Usage: map-monsters.py [rathena dir] [output file]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RATHENA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "server"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "client" / "lib" / "game" / "src" / "map_monster_tables.rs"
# a spawn line, with or without its area ("lasa_dun01\tmonster\t...")
SPAWN = re.compile(r"([a-z0-9_]+)(?:,\d+,\d+(?:,\d+,\d+)?)?\t(?:boss_)?monster\t[^\t]+\t(\d+),(\d+)")


def loaded(conf, seen):
    """The npc files the server loads from `conf`, following its import: lines, in order"""
    files = []
    if not (RATHENA / conf).is_file():
        return []
    for line in (RATHENA / conf).read_text(errors="ignore").splitlines():
        line = line.split("//")[0].strip()
        m = re.match(r"(npc|import):\s*(\S+)", line)
        if not m or m.group(2) in seen:
            continue
        seen.add(m.group(2))
        files += loaded(m.group(2), seen) if m.group(1) == "import" else [m.group(2)]
    return [f for f in files if (RATHENA / f).is_file()]


def main():
    mobs = {}
    for blk in (RATHENA / "db/re/mob_db.yml").read_text(errors="ignore").split("\n  - Id: ")[1:]:
        mob_id = int(blk.split("\n")[0].split()[0])
        name = re.search(r"\n    Name: (.+)", blk)
        level = re.search(r"\n    Level: (\d+)", blk)
        cls = re.search(r"\n    Class: (\w+)", blk)
        boss = "\n    Mvp" in blk or (cls is not None and cls.group(1) == "Boss")
        if name:
            mobs[mob_id] = (name.group(1).strip().strip('"'), int(level.group(1)) if level else 1, boss)

    spawns = {}
    # with our own (npc/custom/mobs: the endgame fields rAthena has no monsters on)
    seen = set()
    for f in loaded("npc/re/scripts_main.conf", seen) + loaded("npc/scripts_custom.conf", seen):
        # the spawn lists, and episodes that keep theirs beside their NPCs (npc/re/custom/lasagna)
        if "/mobs/" not in f and "/custom/lasagna/" not in f:
            continue
        for line in (RATHENA / f).read_text(errors="ignore").splitlines():
            m = SPAWN.match(line)
            if m and int(m.group(2)) in mobs:
                on_map = spawns.setdefault(m.group(1), {})
                on_map[int(m.group(2))] = on_map.get(int(m.group(2)), 0) + int(m.group(3))

    used = sorted({i for on_map in spawns.values() for i in on_map})
    lines = [
        "// Generated by scripts/map-monsters.py from rAthena's monster spawns and db/re/mob_db.yml; do not edit.",
        "",
        "/// A map's monsters: (monster id, how many spawn), by level",
        "pub fn map_monsters(map: &str) -> &'static [(u16, u16)] {",
        "    MAPS.binary_search_by(|(name, _)| (*name).cmp(map))",
        "        .map_or(&[], |i| MAPS[i].1)",
        "}",
        "",
        "/// A monster's English name, level and whether it is a boss or MVP",
        "pub fn monster_info(id: u16) -> Option<(&'static str, u16, bool)> {",
        "    MONSTERS.binary_search_by_key(&id, |(i, ..)| *i)",
        "        .ok()",
        "        .map(|i| (MONSTERS[i].1, MONSTERS[i].2, MONSTERS[i].3))",
        "}",
        "",
        f"static MAPS: [(&str, &[(u16, u16)]); {len(spawns)}] = [",
    ]
    for name in sorted(spawns):
        on_map = sorted(spawns[name].items(), key=lambda ic: (mobs[ic[0]][1], ic[0]))
        lines.append(f'    ("{name}", &[' + ", ".join(f"({i}, {c})" for i, c in on_map) + "]),")
    lines += ["];", "", f"static MONSTERS: [(u16, &str, u16, bool); {len(used)}] = ["]
    for i in used:
        name, level, boss = mobs[i]
        escaped = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    ({i}, "{escaped}", {level}, {str(boss).lower()}),')
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(spawns)} maps, {len(used)} monsters -> {OUT}")


if __name__ == "__main__":
    main()
